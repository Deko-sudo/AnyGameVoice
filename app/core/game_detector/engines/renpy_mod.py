"""Reversible Ren'Py voice mod: engine dialogue IDs + config.auto_voice.

Voice files and one generated script live in ``game/anygamevoice/``. The game's
own scripts are never edited. Dialogue identifiers come from Ren'Py's own
``dialogue`` export, not from AnyGameVoice's internal hashes.
"""

import csv
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import uuid

from app.utils.atomic import atomic_json

__all__ = [
    "MOD_DIR", "find_sdk", "game_root", "export_dialogue_ids", "plan_install",
    "install_mod", "verify_mod", "uninstall_mod", "check_owned",
]

MOD_DIR = "anygamevoice"
SCHEMA = "anygamevoice-renpy-mod"
MANIFEST = "anygamevoice-mod.json"
SCRIPT = "anygamevoice_voice.rpy"
VOICE_PATTERN = MOD_DIR + "/voice/{id}.wav"
_ID_RE = re.compile(r"^[A-Za-z0-9_]{1,200}$")
_AUTO_VOICE_RE = re.compile(r"^\s*(?:define\s+|\$\s*)?config\.auto_voice\s*=", re.MULTILINE)
# Files Ren'Py itself compiles next to our script; allowed inside the mod folder.
_ENGINE_FILES = {SCRIPT + "c"}

GENERATED_SCRIPT = f'''# Generated by AnyGameVoice. Do not edit: verify/uninstall check checksums.
# Uninstall with: python app/main.py renpy uninstall <game_folder>
init 1100 python:
    if config.auto_voice is None:
        config.auto_voice = "{VOICE_PATTERN}"
    else:
        renpy.log("AnyGameVoice: the game already sets config.auto_voice; the voice mod is inactive.")
'''


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _normalize(text: str) -> str:
    return " ".join(text.replace("\\n", " ").split())


def find_sdk(sdk: str | os.PathLike | None = None) -> Path:
    """Return the Ren'Py launcher script from an explicit path or AGV_RENPY_SDK."""
    value = sdk or os.environ.get("AGV_RENPY_SDK", "")
    if not value:
        raise ValueError("Укажите Ren'Py SDK: --sdk <папка SDK> или переменная AGV_RENPY_SDK.")
    path = Path(value).expanduser().resolve()
    launcher = path / "renpy.sh" if path.is_dir() else path
    if not launcher.is_file():
        raise ValueError(f"Не найден renpy.sh в {path}.")
    return launcher


def game_root(path: str | os.PathLike) -> Path:
    """The Ren'Py base directory: the folder that contains ``game/``."""
    root = Path(path).expanduser().resolve()
    if root.name == "game" and not (root / "game").is_dir():
        root = root.parent
    if not (root / "game").is_dir() or (root / "game").is_symlink():
        raise ValueError("Это не папка Ren'Py-игры: внутри нет каталога game.")
    return root


def export_dialogue_ids(path, sdk=None, timeout: int = 300) -> list[dict]:
    """Run Ren'Py's own dialogue export and return its rows.

    Ren'Py writes ``dialogue.tab`` to the game root; it is read and removed.
    Logs go to a temporary folder. Ren'Py may compile ``.rpyc`` caches as it
    would on a normal launch.
    """
    root = game_root(path)
    launcher = find_sdk(sdk)
    table = root / "dialogue.tab"
    if table.exists():
        raise ValueError("В папке игры уже есть dialogue.tab. Переместите его, чтобы не перезаписать.")
    leftovers = [name for name in ("traceback.txt", "errors.txt") if not (root / name).exists()]
    with tempfile.TemporaryDirectory(prefix="agv-renpy-log-") as logs:
        env = {**os.environ, "SDL_VIDEODRIVER": "dummy", "SDL_AUDIODRIVER": "dummy",
               "RENPY_PERFORMANCE_TEST": "0", "RENPY_LOG_BASE": logs}
        try:
            proc = subprocess.run([str(launcher), str(root), "dialogue", "None", "--notags"],
                                  capture_output=True, timeout=timeout, env=env, stdin=subprocess.DEVNULL)
        except subprocess.TimeoutExpired as exc:
            raise RuntimeError("Ren'Py не завершил экспорт реплик вовремя.") from exc
        try:
            if proc.returncode or not table.is_file():
                detail = (root / "traceback.txt").read_text(errors="replace")[:500] if (root / "traceback.txt").is_file() else proc.stderr.decode(errors="replace")[-500:]
                raise RuntimeError("Ren'Py не смог экспортировать реплики: " + detail.strip())
            with table.open(encoding="utf-8-sig", newline="") as fh:
                rows = list(csv.DictReader(fh, delimiter="\t", quoting=csv.QUOTE_NONE))
        finally:
            table.unlink(missing_ok=True)
            for name in leftovers:
                (root / name).unlink(missing_ok=True)
    for row in rows:
        if not _ID_RE.match(row.get("Identifier") or ""):
            raise ValueError(f"Неожиданный идентификатор реплики Ren'Py: {row.get('Identifier')!r}")
    return rows


def _script_relative(filename: str) -> str:
    name = filename.replace("\\", "/")
    return name[len("game/"):] if name.startswith("game/") else name


def plan_install(result: dict, rows: list[dict]) -> dict:
    """Match a finished batch to engine dialogue IDs by script file, line and text."""
    if result.get("status") != "done":
        raise ValueError("Устанавливается только полностью готовая озвучка.")
    by_location = {}
    duplicates = set()
    for row in rows:
        key = (_script_relative(row["Filename"]), int(row["Line Number"]))
        if key in by_location:
            duplicates.add(key)
        by_location[key] = row
    matched, unmatched = [], []
    for item in result["lines"]:
        key = (item.get("source_file", ""), int(item.get("line_no") or 0))
        row = by_location.get(key)
        if row is None or key in duplicates:
            unmatched.append(item["id"])
            continue
        if _normalize(row["Dialogue"]) != _normalize(item.get("metadata", {}).get("original_text", item["text"])):
            raise ValueError(f"Текст реплики {key[0]}:{key[1]} изменился. Создайте озвучку повторно.")
        matched.append((row["Identifier"], item))
    ids = [identifier for identifier, _ in matched]
    if len(set(ids)) != len(ids):
        raise ValueError("Несколько файлов озвучки указывают на одну реплику Ren'Py.")
    if not matched:
        raise ValueError("Ни одна реплика не совпала с экспортом Ren'Py.")
    return {"matched": matched, "unmatched": unmatched, "engine_total": len(rows)}


def _sources_set_auto_voice(game_dir: Path) -> list[str]:
    hits = []
    for script in game_dir.rglob("*.rpy"):
        relative = script.relative_to(game_dir)
        if relative.parts[0] == MOD_DIR:
            continue
        if _AUTO_VOICE_RE.search(script.read_text(encoding="utf-8", errors="replace")):
            hits.append(relative.as_posix())
    return hits


def check_owned(target: Path, root: Path) -> dict:
    """Refuse to touch a mod folder that is not exactly what AnyGameVoice installed."""
    if target.is_symlink():
        raise ValueError("Папка мода не должна быть ссылкой.")
    try:
        data = json.loads((target / MANIFEST).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ValueError("В game/anygamevoice есть сторонние файлы. Установка остановлена.") from exc
    if data.get("schema") != SCHEMA or data.get("game_path") != str(root):
        raise ValueError("Папка мода принадлежит другому проекту.")
    if any(p.is_symlink() for p in target.rglob("*")):
        raise ValueError("В папке мода обнаружена символическая ссылка.")
    expected = {}
    for item in data["files"]:
        relative = Path(item["path"])
        if relative.is_absolute() or ".." in relative.parts:
            raise ValueError("Повреждённый манифест мода.")
        expected[relative.as_posix()] = item["sha256"]
    for relative, digest in expected.items():
        path = target / relative
        if not path.is_file() or _sha256(path) != digest:
            raise ValueError(f"Файл мода изменён или удалён: {relative}. Сохраните изменения и переустановите.")
    actual = {p.relative_to(target).as_posix() for p in target.rglob("*") if p.is_file()}
    extra = actual - set(expected) - {MANIFEST} - _ENGINE_FILES
    if extra:
        raise ValueError("В папке мода появились сторонние файлы: " + ", ".join(sorted(extra)[:5]))
    return data


def _move_to_backup(target: Path, root: Path, prefix: str = "") -> Path:
    backups = root / ".anygamevoice-backups"
    if backups.is_symlink():
        raise ValueError("Папка резервных копий не должна быть ссылкой.")
    backups.mkdir(exist_ok=True)
    destination = backups / f"{prefix}renpy-{uuid.uuid4().hex}"
    target.rename(destination)
    return destination


def check_install_target(path) -> Path:
    """Reject incompatible voice configuration or foreign files before synthesis."""
    root = game_root(path)
    game_dir = root / "game"
    conflicts = _sources_set_auto_voice(game_dir)
    if conflicts:
        raise ValueError("Игра уже задаёт config.auto_voice (" + ", ".join(conflicts[:3]) + "). Установка не выполнена.")
    target = game_dir / MOD_DIR
    if target.exists() or target.is_symlink():
        check_owned(target, root)
    return root


def install_mod(result: dict, sdk=None, rows: list[dict] | None = None, cancel_event=None) -> dict:
    """Install a verified batch as ``game/anygamevoice`` (atomic, reversible)."""
    root = check_install_target(result["game_path"])
    game_dir = root / "game"
    rows = export_dialogue_ids(root, sdk) if rows is None else rows
    plan = plan_install(result, rows)
    output = Path(result["out"]).resolve()
    target = game_dir / MOD_DIR
    if target.exists():
        check_owned(target, root)
    with tempfile.TemporaryDirectory(prefix=".agv-stage-", dir=root) as temporary:
        stage = Path(temporary) / MOD_DIR
        (stage / "voice").mkdir(parents=True)
        files = []
        for identifier, item in plan["matched"]:
            if cancel_event is not None and cancel_event.is_set():
                raise InterruptedError("Установка остановлена. Игра не изменена.")
            source = (output / Path(item["filename"]).name).resolve()
            if source.parent != output or not source.is_file() or _sha256(source) != item.get("sha256"):
                raise ValueError("Файл озвучки изменён после генерации. Создайте озвучку повторно.")
            relative = f"voice/{identifier}.wav"
            shutil.copyfile(source, stage / relative)
            files.append({"path": relative, "sha256": item["sha256"], "id": identifier, "line": item["id"]})
        (stage / SCRIPT).write_text(GENERATED_SCRIPT, encoding="utf-8")
        files.append({"path": SCRIPT, "sha256": _sha256(stage / SCRIPT)})
        atomic_json(stage / MANIFEST, {"schema": SCHEMA, "game_path": str(root), "voice_pattern": VOICE_PATTERN,
                                       "engine_total": plan["engine_total"], "files": files})
        if cancel_event is not None and cancel_event.is_set():
            raise InterruptedError("Установка остановлена. Игра не изменена.")
        backup = None
        if target.exists():
            check_owned(target, root)
            backup = _move_to_backup(target, root)
        try:
            stage.rename(target)
        except Exception:
            if backup:
                backup.rename(target)
            raise
    voiced = len(plan["matched"])
    return {"status": "installed", "engine": "renpy", "path": str(target), "voiced": voiced,
            "engine_total": plan["engine_total"], "unmatched": plan["unmatched"],
            "backup": str(backup) if backup else "",
            "note": f"Мод установлен: {voiced} из {plan['engine_total']} реплик Ren'Py. Перезапустите игру."}


def verify_mod(path, sdk=None) -> dict:
    """Check installed files against the manifest; with an explicit SDK, also check IDs still exist."""
    root = game_root(path)
    target = root / "game" / MOD_DIR
    if not target.exists():
        return {"status": "absent", "path": str(target)}
    data = check_owned(target, root)
    ids = {item["id"] for item in data["files"] if "id" in item}
    report = {"status": "ok", "path": str(target), "voiced": len(ids)}
    if sdk is not None:
        current = {row["Identifier"] for row in export_dialogue_ids(root, sdk)}
        stale = sorted(ids - current)
        report.update(engine_total=len(current), stale=stale)
        if stale:
            report["status"] = "stale"
    return report


def uninstall_mod(path) -> dict:
    """Move the owned mod folder out of game/ into .anygamevoice-backups."""
    root = game_root(path)
    target = root / "game" / MOD_DIR
    if not target.exists():
        return {"status": "absent", "path": str(target)}
    check_owned(target, root)
    destination = _move_to_backup(target, root, prefix="removed-")
    return {"status": "removed", "path": str(destination),
            "note": "Мод удалён из игры и сохранён в .anygamevoice-backups. Перезапустите игру."}
